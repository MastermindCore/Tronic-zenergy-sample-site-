async function loadDashboard() {
  await window.TZ_FIREBASE.initFirebase();
  const user = await window.TZ_AUTH.tzCurrentUser();
  if (!user) {
    window.location.href = "login.html";
    return;
  }

  document.getElementById("welcome-name").textContent = user.name || user.displayName || "there";

  const params = new URLSearchParams(window.location.search);
  const buyTarget = params.get("buy");
  if (buyTarget) await handlePurchase(buyTarget);

  const modules = window.TZ_FIREBASE.DEMO_MODE
    ? window.TZ_DEMO.classes.modules
    : await fetchModulesFromRtdb();

  const enrollments = window.TZ_FIREBASE.DEMO_MODE
    ? (window.TZ_DEMO.getUser() || {}).enrollments || {}
    : await fetchEnrollments(user.uid);

  renderModuleList(modules, enrollments);

  const hasAnyPaid = Object.values(enrollments).some((e) => e.paid);
  document.getElementById("qa-section").style.display = hasAnyPaid ? "block" : "none";
  if (!hasAnyPaid) {
    document.getElementById("qa-locked-note").style.display = "block";
  }
}

async function fetchModulesFromRtdb() {
  const { rtdb, dbMod } = window.__tz;
  const snap = await dbMod.get(dbMod.ref(rtdb, "modules"));
  if (!snap.exists()) return [];
  return Object.entries(snap.val()).map(([id, v]) => ({ id, ...v, topics: Array.isArray(v.topics) ? v.topics : Object.entries(v.topics || {}).map(([tid, t]) => ({ id: tid, ...t })) })).sort((a, b) => a.order - b.order);
}

async function fetchEnrollments(uid) {
  const { rtdb, dbMod } = window.__tz;
  const snap = await dbMod.get(dbMod.ref(rtdb, `users/${uid}/enrollments`));
  return snap.exists() ? snap.val() : {};
}

async function handlePurchase(target) {
  if (window.TZ_FIREBASE.DEMO_MODE) {
    window.TZ_DEMO.enroll(target);
    alert("Demo mode: payment auto-confirmed. In production this opens the checkout Cloud Function below.");
    window.history.replaceState({}, "", "dashboard.html");
    return;
  }

  const { functions, fnMod } = window.__tz;
  const startCheckout = fnMod.httpsCallable(functions, "startCheckout");
  try {
    const res = await startCheckout({ moduleId: target });
    if (res.data.url) {
      window.location.href = res.data.url; // Flutterwave hosted checkout
    }
  } catch (err) {
    alert("Could not start checkout: " + err.message);
  } finally {
    window.history.replaceState({}, "", "dashboard.html");
  }
}

function renderModuleList(modules, enrollments) {
  const list = document.getElementById("module-list");
  list.innerHTML = "";

  const purchased = modules.filter((m) => enrollments[m.id] && enrollments[m.id].paid);

  if (!purchased.length) {
    list.innerHTML = `<div class="card center"><p style="margin-bottom:16px">You haven't enrolled in a module yet.</p><a class="btn btn-primary" href="classes.html">Browse modules</a></div>`;
    return;
  }

  purchased.forEach((mod) => {
    const enrollment = enrollments[mod.id];
    const totalTopics = mod.topics.length;
    const doneTopics = Object.keys(enrollment.progress || {}).length;
    const pct = totalTopics ? Math.round((doneTopics / totalTopics) * 100) : 0;
    const status = enrollment.passed ? "done" : "active";

    const row = document.createElement("div");
    row.className = "card";
    row.style.marginBottom = "16px";
    row.innerHTML = `
      <div style="display:flex;justify-content:space-between;align-items:flex-start;gap:16px;flex-wrap:wrap">
        <div>
          <span class="tag tag-cyan">${mod.level}</span>
          <h3 style="margin:8px 0 6px">${mod.title}</h3>
        </div>
        <span class="tag ${status === "done" ? "tag-done" : "tag-electric"}">
          ${status === "done" ? "Certified" : "In progress"}
        </span>
      </div>
      <div class="progress-track" style="margin:12px 0 8px"><div class="progress-fill" style="width:${pct}%"></div></div>
      <p style="margin:0 0 14px;font-size:0.85rem">${doneTopics} of ${totalTopics} lessons complete${enrollment.examScore != null ? ` &middot; exam score ${enrollment.examScore}%` : ""}</p>
      <a class="btn btn-ghost" href="module.html?m=${mod.id}">${status === "done" ? "Review module" : "Continue module"}</a>
      ${status === "done" ? `<a class="btn btn-cyan" style="margin-left:8px" ${enrollment.certificateUrl ? `href="${enrollment.certificateUrl}" target="_blank" rel="noopener"` : `href="#" data-cert="${mod.id}"`}>Download certificate</a>` : ""}
    `;
    list.appendChild(row);
  });

  list.querySelectorAll("[data-cert]").forEach((btn) => {
    btn.addEventListener("click", (e) => {
      e.preventDefault();
      alert("In production this downloads the PDF certificate generated by the onExamPassed Cloud Function.");
    });
  });
}

async function submitQaRequest(e) {
  e.preventDefault();
  const day = document.getElementById("qa-day").value;
  const time = document.getElementById("qa-time").value;
  const note = document.getElementById("qa-note").value.trim();
  const statusEl = document.getElementById("qa-status");

  await window.TZ_FIREBASE.initFirebase();
  const user = await window.TZ_AUTH.tzCurrentUser();

  if (window.TZ_FIREBASE.DEMO_MODE) {
    statusEl.textContent = `Request sent for ${day} around ${time}. In production, Ezra confirms and a calendar invite with a Meet link arrives by email.`;
    statusEl.style.display = "block";
    return;
  }

  const { rtdb, dbMod } = window.__tz;
  await dbMod.push(dbMod.ref(rtdb, "qaRequests"), {
    uid: user.uid,
    name: user.displayName,
    email: user.email,
    preferredDay: day,
    preferredTime: time,
    note,
    status: "pending",
    createdAt: dbMod.serverTimestamp(),
  });
  statusEl.textContent = "Request sent. You'll get a confirmation email once Ezra accepts a slot.";
  statusEl.style.display = "block";
}

document.addEventListener("DOMContentLoaded", () => {
  loadDashboard();
  document.getElementById("logout-btn").addEventListener("click", async () => {
    await window.TZ_AUTH.tzLogOut();
    window.location.href = "index.html";
  });
  document.getElementById("qa-form").addEventListener("submit", submitQaRequest);
});
